"""Generate two labeled, offline-only PCAP fixtures; never send any packets."""
from __future__ import annotations
import argparse
import ipaddress
import json
import struct
from pathlib import Path


def checksum(data: bytes) -> int:
    if len(data)%2:data+=b'\x00'
    value=sum(struct.unpack('!'+str(len(data)//2)+'H',data))
    while value>>16:value=(value&0xffff)+(value>>16)
    return (~value)&0xffff


def frame(src: str, dst: str, sport: int, dport: int, seq: int, ack: int, flags: int, payload: bytes=b'') -> bytes:
    a,b=ipaddress.ip_address(src).packed,ipaddress.ip_address(dst).packed
    tcp=struct.pack('!HHIIBBHHH',sport,dport,seq,ack,5<<4,flags,65535,0,0)+payload
    check=checksum(a+b+struct.pack('!BBH',0,6,len(tcp))+tcp)
    tcp=tcp[:16]+struct.pack('!H',check)+tcp[18:]
    ip=struct.pack('!BBHHHBBH4s4s',0x45,0,20+len(tcp),1,0,64,6,0,a,b)
    ip=ip[:10]+struct.pack('!H',checksum(ip))+ip[12:]
    return bytes.fromhex('0200000000020200000000010800')+ip+tcp


def capture(source: str, function: int) -> bytes:
    dst='192.0.2.10';port=40000
    request=struct.pack('!HHHBBHH',1,0,6,1,function,0,1)
    response=request if function==6 else struct.pack('!HHHBBB H',1,0,5,1,3,2,42)
    packets=[frame(source,dst,port,502,100,0,2),frame(dst,source,502,port,200,101,18),
             frame(source,dst,port,502,101,201,16),frame(source,dst,port,502,101,201,24,request),
             frame(dst,source,502,port,201,101+len(request),24,response),
             frame(source,dst,port,502,101+len(request),201+len(response),17),
             frame(dst,source,502,port,201+len(response),102+len(request),17)]
    out=struct.pack('<IHHIIII',0xa1b2c3d4,2,4,0,0,65535,1)
    for i,packet in enumerate(packets):out+=struct.pack('<IIII',1793246400,i*1000,len(packet),len(packet))+packet
    return out


def generate(directory: Path):
    directory.mkdir(parents=True,exist_ok=True)
    files={'synthetic-benign-read.pcap':capture('192.0.2.30',3),'synthetic-unauthorized-write.pcap':capture('192.0.2.99',6),
           'policy.json':json.dumps({'protected_assets':['192.0.2.10'],'authorized_writers':{'192.0.2.10':['192.0.2.30']},'allowed_communications':[{'source_ip':'192.0.2.30','destination_ip':'192.0.2.10','destination_port':502,'protocol':'tcp'}],'maintenance_windows_utc':[{'days':[3],'start':'01:00','end':'03:00'}]},indent=2).encode(),
           'README.txt':b'SYNTHETIC OFFLINE TEST CAPTURES ONLY. No real devices or observed incidents. Generated bytes were never transmitted. Analyze only as files using Zeek.\n'}
    for name,data in files.items():
        target=directory/name
        if target.exists():raise FileExistsError(f'Refusing to overwrite {target}')
    for name,data in files.items():(directory/name).write_bytes(data)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--output-dir',type=Path,default=Path('data/passive-demo'))
    args=parser.parse_args();generate(args.output_dir);print(f'Created labeled offline-only captures in {args.output_dir}; no packets were transmitted.')
